package main

import "strings"

// t2s 只涵盖测速点解析会用到的字（省份、城市、运营商、行政区后缀），
// 让繁体输入也能匹配，例如「廣東電信」「臺北」「瀋陽聯通」。
var t2sPairs = []string{
	// 运营商
	"電", "电", "聯", "联", "動", "动",
	// 行政区后缀
	"區", "区", "別", "别", "壯", "壮", "爾", "尔",
	// 省份
	"東", "东", "廣", "广", "寧", "宁", "內", "内", "雲", "云", "貴", "贵",
	"遼", "辽", "陝", "陕", "肅", "肃", "慶", "庆", "蘇", "苏", "龍", "龙",
	"灣", "湾", "臺", "台", "門", "门", "維", "维",
	// 城市
	"莊", "庄", "瀋", "沈", "陽", "阳", "長", "长", "濱", "滨", "濟", "济",
	"鄭", "郑", "漢", "汉", "薩", "萨", "蘭", "兰", "銀", "银", "烏", "乌",
	"魯", "鲁", "齊", "齐", "島", "岛", "廈", "厦", "無", "无", "錫", "锡",
}

var t2s = strings.NewReplacer(t2sPairs...)

func toSimplified(s string) string { return t2s.Replace(s) }
